#!/usr/bin/env bash
# PreToolUse (Edit|Write): block edits to generated and protected files.
#
# Enforces: Claude does not hand-edit
#   - dependency folders (node_modules), build output (bin, obj) and coverage output
#   - package-lock.json (change package.json and run npm install)
#   - EF Core generated *.Designer.cs files in a Migrations folder
#   - any path in "protectedPaths" in .claude/ifeelfine.json
#
# Why: these files are produced by tools. A hand edit is lost or breaks the next
# generation, and the right fix is always to change the source and rerun the tool.
#
# Config (.claude/ifeelfine.json), optional:
#   "protectedPaths": [ { "glob": "docs/diagrams/*.png", "message": "Rendered. Edit the source." } ]
# A glob without a slash also matches in any folder. Matching ignores case.
#
# Needs jq. Without it the hook exits 0 and does nothing.

# shellcheck source=lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
need_tool jq
read_input

file_path="$(json_get tool_input.file_path)"
[[ -z "$file_path" ]] && exit 0
rel="$(normalize_path "$file_path")"
shopt -s nocasematch

case "$rel" in
  */node_modules/* | node_modules/*)
    block "$rel is a dependency directory." ;;
  */bin/* | */obj/*)
    block "$rel is a build output." ;;
  */coverage/* | */coverage-*/* | coverage-*/*)
    block "$rel is a coverage output." ;;
  */package-lock.json | package-lock.json)
    block "$rel is generated. Change package.json and run npm install." ;;
  */Migrations/*.Designer.cs)
    block "$rel is generated by dotnet ef. Scaffold a new migration instead." ;;
esac

while IFS=$'\t' read -r glob message; do
  [[ -z "$glob" ]] && continue
  # shellcheck disable=SC2254  # the config glob is meant to act as a pattern
  case "$rel" in
    $glob | */$glob)
      block "$rel is protected. $message" ;;
  esac
done < <(cfg_protected_paths)

exit 0
